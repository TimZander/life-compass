/**
 * The question definitions, written into `src/client` as a module the client can import.
 *
 * The client needs them — #67 to build a prompt for a group, #68 to check a reply against
 * the group it names — and it cannot fetch them: `connect-src 'none'` (docs/decisions/0006,
 * 0007 · C1) blocks the request before the service worker ever sees it, and that rule is the
 * privacy claim rather than an obstacle in front of it. So the schema arrives as script,
 * which `script-src 'self'` already permits. docs/decisions/0015 records the choice.
 *
 * Generated into the source tree rather than straight into `dist`, which #71 tried first.
 * That version typechecked against a `.d.ts` and emitted the real module only into the
 * output, so `tsc` was satisfied and Node could not resolve the import at all — every test
 * touching a module that imported the schema failed to load. Nothing imported it yet, so
 * nothing noticed. Writing a `.ts` instead means one file serves all three consumers: Node
 * runs it from source, `tsc -p tsconfig.client.json` checks it, and `buildClient` discovers
 * it like any other module and needs no special case.
 *
 * It is generated, so it is git-ignored and rebuilt by the `prepare`, `pretest`,
 * `pretypecheck` and `prebuild` hooks. What guards it is not those hooks — a hook can be
 * skipped by `node --run`, by `npm run serve`, by `npm ci --ignore-scripts`, or by running
 * `tsc` directly — but `checkSpecifiers` in build/client.ts, which refuses to emit a module
 * graph containing an import nothing satisfies. Missing means a failed build rather than a
 * shipped site whose client is dead.
 *
 * `--check` regenerates to memory and compares, so CI can fail on a file that drifted from
 * the definitions rather than only on one that is absent.
 */

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { CLIENT_DIR } from "./client.ts";
import { checkSchema, loadSchema } from "./questions.ts";
import { WORKSHEETS, type Worksheet } from "../src/questions/index.ts";

/**
 * Derived from `CLIENT_DIR` rather than written again.
 *
 * If the client tier ever moves, a second copy of its path would leave the generator writing
 * where nothing looks — and because the file is git-ignored, the failure would be a build
 * that emits no schema module. The same "two copies of one fact" objection this repository
 * keeps recording, applied to a path.
 */
export const SCHEMA_MODULE: string = `${CLIENT_DIR}/schema.ts`;

/**
 * The module's source.
 *
 * `import type` so the emit erases it: `build/client.ts` rewrites relative specifiers to
 * `.js`, and `../questions/index.js` is not a file the browser will ever be served. A value
 * import would 404 the whole module; a type import is gone before it ships.
 *
 * The relative specifier is derived from where the module lands, so it cannot fall out of
 * step with `SCHEMA_MODULE` above.
 */
export function schemaSource(worksheets: readonly Worksheet[]): string {
  const toQuestions = path.posix.relative(path.posix.dirname(SCHEMA_MODULE), "src/questions");
  return (
    `// Generated by build/schema.ts. Editing this file achieves nothing — it is rewritten\n` +
    `// by the prepare, pretest, pretypecheck and prebuild hooks, and git ignores it.\n` +
    `//\n` +
    `// The question definitions, served to the page as script because connect-src 'none'\n` +
    `// means it cannot fetch them (docs/decisions/0015).\n` +
    `import type { Worksheet } from "${toQuestions}/index.ts";\n\n` +
    `export const WORKSHEETS: readonly Worksheet[] = ${JSON.stringify(worksheets, null, 2)};\n`
  );
}

/**
 * Write it, having first held the definitions to the same checks the build applies.
 *
 * `build()` runs `checkSchema` before it writes anything, and refuses on a problem. This ran
 * from raw `WORKSHEETS` and so could hand the client a schema the build would have rejected —
 * and it runs FIRST, from `pretest` and `pretypecheck`, so it would be the copy every check
 * then agreed with.
 */
export async function writeSchemaModule(root: string): Promise<void> {
  const problems = checkSchema(loadSchema(WORKSHEETS));
  if (problems.length > 0) {
    const detail = problems.map((problem) => `  ${problem}`).join("\n");
    throw new Error(`refusing to write the client schema; the definitions are broken:\n${detail}`);
  }

  const destination = path.join(root, SCHEMA_MODULE);
  // The target is inside the SOURCE tree and git-ignored, so a mistaken path here destroys
  // something unrecoverable rather than something a rebuild replaces. build/build.ts guards
  // its own `rm` the same way, and for the same reason.
  if (!destination.endsWith(path.join("src", "client", "schema.ts"))) {
    throw new Error(`refusing to write the client schema to ${destination}`);
  }
  await writeFile(destination, schemaSource(WORKSHEETS), "utf8");
}

/** Whether what is on disk is what the definitions would produce right now. */
export async function schemaModuleIsCurrent(root: string): Promise<boolean> {
  try {
    const onDisk = await readFile(path.join(root, SCHEMA_MODULE), "utf8");
    return onDisk === schemaSource(WORKSHEETS);
  } catch {
    return false;
  }
}

if (process.argv[1] !== undefined && import.meta.filename === path.resolve(process.argv[1])) {
  const root = path.join(import.meta.dirname, "..");
  if (process.argv.includes("--check")) {
    if (!(await schemaModuleIsCurrent(root))) {
      console.error(
        `${SCHEMA_MODULE} is missing or does not match src/questions. Run \`npm run schema\`.`,
      );
      process.exit(1);
    }
    console.log(`ok  ${SCHEMA_MODULE} matches the definitions`);
  } else {
    await writeSchemaModule(root);
  }
}

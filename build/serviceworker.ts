/**
 * The service worker, generated so its precache list and its cache name both come from
 * the build that produced the pages.
 *
 * Hand-writing the list would mean maintaining a second inventory of the site that
 * silently drifts; deriving the cache name from the content is what makes a deploy
 * actually reach an installed client, since an unchanged name means an unchanged cache.
 */

import { createHash } from "node:crypto";

/**
 * Files Cloudflare Pages consumes rather than serves.
 *
 * `cache.addAll` is atomic: one request that 404s rejects the whole call, the install
 * fails, and the site has no service worker at all. `_headers` is exactly such a file —
 * it is deployed, it is not served, and precaching it would break everything with an
 * error message pointing at the wrong thing.
 */
const NOT_SERVED = /(^|\/)_/;

export type PrecacheEntry = {
  /** URL as the browser will request it. */
  readonly url: string;
  /** Bytes, used only to derive the cache version. */
  readonly content: string | Buffer;
};

/** Anything Pages swallows is not a URL, so it cannot be precached. */
export function precachable(entries: readonly PrecacheEntry[]): readonly PrecacheEntry[] {
  return entries.filter((entry) => !NOT_SERVED.test(entry.url));
}

/**
 * A version that changes exactly when the served bytes change.
 *
 * Both the URL and the content go into the hash: renaming a page without editing it is
 * still a change installed clients need, and hashing content alone would miss it.
 */
export function cacheVersion(entries: readonly PrecacheEntry[]): string {
  const hash = createHash("sha256");
  for (const entry of [...entries].sort((a, b) => (a.url < b.url ? -1 : 1))) {
    hash.update(entry.url);
    hash.update("\u0000");
    hash.update(entry.content);
    hash.update("\u0000");
  }
  return hash.digest("hex").slice(0, 16);
}

export function renderServiceWorker(entries: readonly PrecacheEntry[]): string {
  const servable = precachable(entries);
  const version = cacheVersion(servable);
  const urls = [...servable.map((entry) => entry.url)].sort();

  return `// Generated by build/serviceworker.ts. Editing this file achieves nothing.
//
// Every page is precached, not just a shell. The whole site is a few hundred kilobytes
// of text, and a workbook that only half works on a train is worse than one that says
// plainly it needs the network.

const VERSION = ${JSON.stringify(version)};
const CACHE = \`life-compass-\${VERSION}\`;
const PRECACHE = ${JSON.stringify(urls, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      // addAll is atomic on purpose: a partially populated cache would serve some pages
      // offline and fail others, which is harder to diagnose than no cache at all.
      await cache.addAll(PRECACHE);
      // Deliberately NOT skipWaiting(). A new worker waits until the reader accepts it
      // (assets/js/sw-update.js). Activating here swapped the cache and claimed the open
      // page mid-session, which is the interruption docs/decisions/0001 forbids once
      // answers are being typed.
      //
      // A FIRST install is unaffected: with no active worker there is nothing to wait
      // behind, so it activates and claims immediately.
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(
        names
          .filter((name) => name.startsWith("life-compass-") && name !== CACHE)
          .map((name) => caches.delete(name)),
      );
      await self.clients.claim();
    })(),
  );
});

// The page asks for activation once the reader has accepted the update.
self.addEventListener("message", (event) => {
  if (event.data !== null && typeof event.data === "object" && event.data.type === "SKIP_WAITING") {
    self.skipWaiting();
  }
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") {
    return;
  }
  if (new URL(request.url).origin !== self.location.origin) {
    return;
  }

  event.respondWith(
    (async () => {
      // ignoreSearch so a cache-busting query string still finds the cached page.
      const cached = await caches.match(request, { ignoreSearch: true });
      if (cached !== undefined) {
        return cached;
      }

      try {
        return await fetch(request);
      } catch {
        if (request.mode === "navigate") {
          const fallback = await caches.match("/404");
          if (fallback !== undefined) {
            return fallback;
          }
        }
        return new Response("Offline, and this is not in the cache.", {
          status: 503,
          headers: { "content-type": "text/plain; charset=utf-8" },
        });
      }
    })(),
  );
});
`;
}
